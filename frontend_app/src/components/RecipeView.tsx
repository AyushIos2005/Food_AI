import React from 'react';
import { View } from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { Card, Section, Text_ } from './ui';
import { useTheme } from '@/src/theme/ThemeProvider';
import { spacing } from '@/src/theme/tokens';
import { presentRecipeFields } from '@/src/utils/format';
import type { AiRecipe } from '@/src/types/api';

/** Shared recipe body. Only renders fields the server actually returned. */
export function RecipeView({ recipe, aiGenerated = true }: { recipe: AiRecipe; aiGenerated?: boolean }) {
  const { colors } = useTheme();
  const f = presentRecipeFields(recipe);
  return (
    <View>
      <Text_ variant="display">{f.title}</Text_>
      {f.description ? <Text_ muted style={{ marginTop: spacing.sm }}>{f.description}</Text_> : null}

      <View style={{ flexDirection: 'row', flexWrap: 'wrap', marginTop: spacing.md, gap: spacing.sm }}>
        {f.time ? <Meta icon="time-outline" label={f.time} /> : null}
        {f.servings !== null ? <Meta icon="people-outline" label={`${f.servings} serving${f.servings === 1 ? '' : 's'}`} /> : null}
      </View>

      {f.ingredients.length ? (
        <Section title="Ingredients">
          <Card>
            {f.ingredients.map((item, i) => (
              <Text_ key={`${item}-${i}`} style={{ marginBottom: spacing.sm }}>• {item}</Text_>
            ))}
          </Card>
        </Section>
      ) : null}

      {f.instructions.length ? (
        <Section title="Steps">
          {f.instructions.map((step, i) => (
            <Card key={`${i}-${step.slice(0, 12)}`} style={{ marginBottom: spacing.md, flexDirection: 'row' }}>
              <View style={{ width: 28, height: 28, borderRadius: 14, backgroundColor: colors.primarySoft, alignItems: 'center', justifyContent: 'center', marginRight: spacing.md }}>
                <Text_ variant="caption" style={{ color: colors.primary, fontWeight: '700' }}>{i + 1}</Text_>
              </View>
              <Text_ style={{ flex: 1 }}>{step}</Text_>
            </Card>
          ))}
        </Section>
      ) : null}

      {(f.protein || f.calories || f.proteinSources.length) ? (
        <Section title="Nutrition (estimate)">
          <Card>
            {f.protein ? <Text_ style={{ marginBottom: spacing.xs }}>Protein per serving: {f.protein}</Text_> : null}
            {f.calories ? <Text_ style={{ marginBottom: spacing.xs }}>Calories per serving: {f.calories}</Text_> : null}
            {f.proteinSources.length ? <Text_>Protein sources: {f.proteinSources.join(', ')}</Text_> : null}
            <Text_ variant="caption" muted style={{ marginTop: spacing.sm }}>
              Generated by AI. Estimates only, not verified nutrition data.
            </Text_>
          </Card>
        </Section>
      ) : null}

      {f.notes.length ? (
        <Section title="Precautions & notes">
          <Card style={{ backgroundColor: colors.dangerSoft }}>
            {f.notes.map((n, i) => <Text_ key={i} style={{ marginBottom: spacing.xs }}>• {n}</Text_>)}
            <Text_ variant="caption" muted style={{ marginTop: spacing.sm }}>
              Not medical advice. Check with a qualified professional for health conditions.
            </Text_>
          </Card>
        </Section>
      ) : null}

      {aiGenerated ? <Text_ variant="caption" muted style={{ marginTop: spacing.xl, textAlign: 'center' }}>AI-generated recipe</Text_> : null}
    </View>
  );
}

function Meta({ icon, label }: { icon: React.ComponentProps<typeof Ionicons>['name']; label: string }) {
  const { colors } = useTheme();
  return (
    <View style={{ flexDirection: 'row', alignItems: 'center', backgroundColor: colors.surface, borderRadius: 999, paddingHorizontal: 12, paddingVertical: 6, borderWidth: 1, borderColor: colors.border }}>
      <Ionicons name={icon} size={14} color={colors.textMuted} />
      <Text_ variant="caption" style={{ marginLeft: 6 }}>{label}</Text_>
    </View>
  );
}
